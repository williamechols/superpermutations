# Generate the Lean data files for the kernel-checked bound S(7) >= 5897:
#   K5897/Caps.lean : the chain caps T (x = 0..72) and the knapsack certificate B (W = 0..78)
#   K5897/Tab.lean  : Nat-encoded tables for Halfar's search engine on 7 symbols
# The tables are not trusted: every property the proof uses is checked by the kernel.
import math, sys, itertools

OUT = sys.argv[1]
K = 7
HALFAR_M = [5, 5, 9, 9, 13, 13, 16, 16, 20, 20, 24, 24, 27, 27, 31, 31, 34, 34, 36, 38, 40, 41, 43, 44, 46,
            47, 50, 51, 52, 54, 56, 57, 59, 60, 63, 64, 66, 66, 68, 69, 71, 72, 74, 75, 77, 79, 80, 82, 83,
            85, 85, 86, 88, 89, 91, 92, 93, 94, 96, 98, 99, 100, 107, 110, 111, 112, 113, 114, 115, 116,
            119, 120, 121, 122, 123, 124, 125, 126, 127, 128, 129, 130, 131, 132, 133]

# ---- caps -------------------------------------------------------------------------------------
HI, WMAX, VMAX = 72, 78, 54
s = 1.74
a = max(HALFAR_M[x] - s * x for x in range(HI + 1))
T = [max(HALFAR_M[x], math.floor(a + s * x + 1e-9)) for x in range(HI + 1)]
for x in range(1, HI + 1):
    T[x] = max(T[x], T[x - 1])
B = [0] * (WMAX + 1)
for w in range(WMAX + 1):
    best = B[w - 1] if w else 0
    for h in range(HI + 1):
        if h + 6 <= w:
            best = max(best, B[w - h - 6] + T[h] - h - 5)
    B[w] = best
assert B[WMAX] <= VMAX, B[WMAX]
for x in range(HI + 1):
    for W in range(WMAX + 1):
        if W + x + 6 <= WMAX:
            assert T[x] + B[W] <= B[W + x + 6] + x + 5
print('T =', T)
print('B =', B)

# ---- permutation codes, in the order of PS.permCodes 7 7 ---------------------------------------
def perm_codes(k, n):
    if n == 0:
        return [0]
    out = []
    for c in perm_codes(k, n - 1):
        digits = [(c >> (4 * i)) & 15 for i in range(n - 1)]
        for a_ in range(k):
            if (a_ + 1) not in digits:
                out.append(c * 16 + (a_ + 1))
    return out

codes = perm_codes(K, K)
assert len(codes) == 5040 and codes == sorted(codes)
idx = {c: i for i, c in enumerate(codes)}
M1 = 16 ** (K - 1) - 1
S1 = 4 * (K - 1)

def excF(c): return c % 16 * (M1 + 1) + c // 16
def doorF(x): return (x & (M1 >> 4)) * 256 + (x >> (S1 - 4)) % 16 * 16 + (x >> S1)
def nxtF(c): return doorF(excF(c))
def canonF(c):
    for _ in range(K):
        if c >> S1 == K:
            return c
        c = (c & M1) * 16 + (c >> S1)
    return c

# class indices 0..719 by first appearance; a representative for each class
cls_of_canon, ci, rep = {}, [], []
for i, c in enumerate(codes):
    cc = canonF(c)
    if cc not in cls_of_canon:
        cls_of_canon[cc] = len(rep)
        rep.append(i)
    ci.append(cls_of_canon[cc])
assert len(rep) == 720
nx = [idx[nxtF(c)] for c in codes]

def key(p):  # p: four hex digits, each 1..7
    return (((p >> 12) % 16 * 8 + (p >> 8) % 16) * 8 + (p >> 4) % 16) * 8 + p % 16

buckets = [[] for _ in range(4096)]
for j, c in enumerate(codes):
    buckets[key(c >> 12)].append(j)
assert all(len(b) in (0, 6) for b in buckets)
# check: the bucket of the exit suffix of i is exactly the set of weight-3 successors
for i, c in enumerate(codes):
    succ = [j for j, d in enumerate(codes) if excF(c) % 16 ** 4 == d // 16 ** 3]
    assert sorted(succ) == sorted(buckets[key(excF(c) % 16 ** 4)])

def pack(vals, width):
    n = 0
    for v in reversed(vals):
        assert 0 <= v < 2 ** width
        n = (n << width) | v
    return n

CODE = pack(codes, 28)
CI = pack(ci, 10)
REP = pack(rep, 13)
NX = pack(nx, 13)
BK = pack([b[j] if j < len(b) else 8191 for b in buckets for j in range(6)], 13)

def lean_list(xs): return '[' + ', '.join(map(str, xs)) + ']'

with open(f'{OUT}/Caps.lean', 'w') as f:
    f.write(f'''/-!
# The chain caps for 5,897 (generated by `tools/gen_tables.py`; do not edit)

`Tcap` lists caps for chains on 7 symbols with `x = 0, …, {HI}` holes, and `Bcert` a certificate for the
knapsack over families of chains, for weights `W = 0, …, {WMAX}`. Neither is trusted: the search of
`K5897/Search*.lean` proves the caps, and `K5897/Arith.lean` checks the certificate with
`decide +kernel`.
-/

namespace SuperpermLowerBounds
namespace K5897

/-- Chain caps `T x`, `x = 0..{HI}`: about `{a:.2f} + {s} x`, and never below the largest chain found. -/
def Tcap : List Nat :=
  {lean_list(T)}

/-- Certificate for the knapsack: the largest value `Σ (T h - h - 5)` of a family of chains of total
weight `Σ (h + 6)` at most `W`. -/
def Bcert : List Nat :=
  {lean_list(B)}

end K5897
end SuperpermLowerBounds
''')

with open(f'{OUT}/Tab.lean', 'w') as f:
    f.write(f'''/-!
# Tables of the search on 7 symbols (generated by `tools/gen_tables.py`; do not edit)

A word is its index `i < 5040` in `PS.permCodes 7 7`. Each table is one natural number read with
shifts, so that the kernel looks an entry up with a few operations on big numbers:

* `CODE`: the code of word `i` (28 bits);
* `CI`: the index `< 720` of its rotation class (10 bits); `REP`: a word of each class (13 bits);
* `NX`: the entry of the next block of a row (13 bits);
* `BK`: for each key of four letters, the 6 words that begin with them (13 bits each).

None of them is trusted: `K5897/Enc.lean` checks them against the arithmetic of `PSearch.lean`.
-/

namespace SuperpermLowerBounds
namespace K5897

def CODE : Nat := {hex(CODE)}

def CI : Nat := {hex(CI)}

def REP : Nat := {hex(REP)}

def NX : Nat := {hex(NX)}

def BK : Nat := {hex(BK)}

end K5897
end SuperpermLowerBounds
''')
print('tables written', len(hex(CODE)), len(hex(BK)))

# ---- bit tables of the rules (r < RB, d < DB), bit DB * r + d ---------------------------------
RB, DB = 160, 80
def capF(x): return T[x] if 0 <= x <= HI else 0
def seqBad(r, d): return 0 <= d <= HI and capF(d) < r
def seqKeepN(r, d): return any(d <= x and capF(x) < r + capF(x - d) for x in range(HI + 1))
TB = sum(1 << (DB * r + d) for r in range(RB) for d in range(DB) if seqBad(r, d))
TK = sum(1 << (DB * r + d) for r in range(RB) for d in range(DB) if seqKeepN(r, d))
with open(f'{OUT}/CapTab.lean', 'w') as f:
    f.write(f'''/-!
# The rules of the chain search as bit tables (generated by `tools/gen_tables.py`; do not edit)

Bit `{DB} r + d` of `TB` is `PS.seqBad [Tcap] 0 0 {HI} 0 r d`, and of `TK` it is
`PS.seqKeepN [Tcap] 0 0 {HI} 0 r d`, for `r < {RB}`, `d < {DB}`. `K5897/CapFinal.lean` checks both
against the rules by `decide +kernel`.
-/

namespace SuperpermLowerBounds
namespace K5897

def TB : Nat := {TB}

def TK : Nat := {TK}

end K5897
end SuperpermLowerBounds
''')
print('rule tables written')
